"""Unit tests for the small helper modules: params.py (reads initialize.tex) and texout.py (writes macros).

    make test        (or, from the project root:  python -m pytest tests/test_tools.py)
"""
import pytest

import params
from texout import num, write_macros


def test_params_reads_def_and_newcommand_and_converts_types(tmp_path):
    f = tmp_path / "initialize.tex"
    f.write_text("\\def\\Fval{0.018}\n"
                 "\\newcommand{\\Nval}{256}\n"
                 "\\renewcommand{\\Name}{abc}\n"
                 "% \\def\\Hidden{1}\n"
                 "\\def\\Kval{0.055} % comment after the value\n")
    P = params.load(str(f))
    assert P["Fval"] == 0.018 and isinstance(P["Fval"], float)
    assert P["Nval"] == 256 and isinstance(P["Nval"], int)
    assert P["Name"] == "abc"
    assert P["Kval"] == 0.055
    assert "Hidden" not in P


def test_params_remembers_which_keys_were_read(tmp_path):
    f = tmp_path / "initialize.tex"
    f.write_text("\\def\\A{1}\n\\def\\B{2}\n")
    params.ACCESSED.clear()
    P = params.load(str(f))
    _ = P["A"]
    assert params.ACCESSED == {"A"}


def test_num_formats_digits_only():
    assert num(-0.181523, 4) == "-0.1815"
    assert num(566689, 0) == "566689"


def test_write_macros_writes_one_newcommand_per_item(tmp_path):
    out = tmp_path / "sub" / "example.tex"
    write_macros(str(out), "example.py", [("Alpha", "1.5"), ("Beta", "2")])
    text = out.read_text()
    assert "Generated by example.py" in text
    assert "\\newcommand{\\Alpha}{1.5}" in text
    assert "\\newcommand{\\Beta}{2}" in text


def test_write_macros_rejects_bad_names(tmp_path):
    with pytest.raises(ValueError):
        write_macros(str(tmp_path / "a.tex"), "x.py", [("Has1Digit", "1")])
    with pytest.raises(ValueError):
        write_macros(str(tmp_path / "b.tex"), "x.py", [("Same", "1"), ("Same", "2")])
