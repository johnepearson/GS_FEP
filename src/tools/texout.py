"""Write results as LaTeX macros, for \\input by the paper.

    from texout import num, write_macros
    write_macros("results/example.tex", "example.py",
                 [("EnsOnePartial", num(-0.18152, 4)), ("EnsOneN", num(566689, 0))])

num() writes the digits only. In the paper, \\rr{4}{\\EnsOnePartial} rounds to 4 decimals and sets the minus
sign (siunitx), and \\nn{\\EnsOneN} sets an integer with comma grouping.  Macro names may contain letters only (a TeX rule);
this module raises an error otherwise, and \\newcommand makes LaTeX stop if two scripts define the same name.
"""
import os
import re

_NAME = re.compile(r"^[A-Za-z]+$")


def num(x, ndigits):
    """Number as a plain macro value with ndigits decimals. The paper sets the rounding and the minus sign with
    \\rr{places}{\\Macro} (defined in paper.tex), so store more digits than any table or sentence shows."""
    return f"{x:.{ndigits}f}"


def write_macros(path, script, items):
    """items: list of (name, latex_value).  Writes one \\newcommand per item."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    names = [n for n, _ in items]
    if len(set(names)) != len(names):
        raise ValueError("duplicate macro name in " + script)
    with open(path, "w") as f:
        f.write(f"% Generated by {script}. Do not edit; rerun make.\n")
        for name, value in items:
            if not _NAME.match(name):
                raise ValueError(f"macro name {name!r} must contain letters only")
            f.write("\\newcommand{\\%s}{%s}\n" % (name, value))
